private final class TMSoundBank {
    private var players: [TMSound: AVAudioPlayer] = [:]

    func play(_ sound: TMSound, volume: Float = 0.9) {
        guard let player = players[sound] ?? load(sound) else { return }
        player.volume = volume
        player.currentTime = 0
        player.play()
    }

    func stopAll() {
        for player in players.values { player.stop() }
    }

    private func load(_ sound: TMSound) -> AVAudioPlayer? {
        let url = Bundle.main.url(forResource: sound.rawValue, withExtension: "wav", subdirectory: "TimeMotionSounds")
            ?? Bundle.main.url(forResource: sound.rawValue, withExtension: "wav")
        guard let url, let player = try? AVAudioPlayer(contentsOf: url) else { return nil }
        player.prepareToPlay()
        players[sound] = player
        return player
    }
}

private func tmConstantMaterial(_ color: UIColor) -> SCNMaterial {
    let material = SCNMaterial()
    material.lightingModel = .constant
    material.diffuse.contents = color
    material.isDoubleSided = true
    return material
}

/// Renders text into an image so Cyrillic and emoji stay readable in VR.
private func tmLabelImage(_ value: String, color: UIColor) -> UIImage? {
    guard !value.isEmpty else { return nil }
    let font = UIFont.systemFont(ofSize: 52, weight: .bold)
    let attributes: [NSAttributedString.Key: Any] = [.font: font, .foregroundColor: color]
    let string = NSAttributedString(string: value, attributes: attributes)
    let bounds = string.boundingRect(with: CGSize(width: 4000, height: 4000),
                                     options: [.usesLineFragmentOrigin, .usesFontLeading], context: nil)
    let size = CGSize(width: ceil(bounds.width) + 2, height: ceil(bounds.height) + 2)
    guard size.width > 2, size.height > 2 else { return nil }
    let format = UIGraphicsImageRendererFormat()
    format.scale = 1
    format.opaque = false
    return UIGraphicsImageRenderer(size: size, format: format).image { _ in
        string.draw(with: CGRect(x: 1, y: 1, width: bounds.width, height: bounds.height),
                    options: [.usesLineFragmentOrigin, .usesFontLeading], context: nil)
    }
}

private final class TMLabel: SCNNode {
    private var current = ""
    private let plane = SCNPlane(width: 1, height: 1)
    private let planeNode = SCNNode()

    override init() {
        super.init()
        constraints = [SCNBillboardConstraint()]
        let material = SCNMaterial()
        material.lightingModel = .constant
        material.isDoubleSided = true
        material.diffuse.contents = UIColor.clear
        plane.materials = [material]
        planeNode.geometry = plane
        addChildNode(planeNode)
    }

    required init?(coder: NSCoder) {
        fatalError("init(coder:) has not been implemented")
    }

    /// `meters` is the width of the text in the world.
    func setText(_ value: String, color: UIColor = .white, meters: Float) {
        guard value != current else { return }
        current = value
        guard let image = tmLabelImage(value, color: color), image.size.width > 1 else {
            planeNode.isHidden = true
            return
        }
        plane.width = image.size.width
        plane.height = image.size.height
        plane.firstMaterial?.diffuse.contents = image
        let factor = meters / Float(image.size.width)
        scale = SCNVector3(factor, factor, factor)
        planeNode.isHidden = false
    }
}

