private final class TMEnemy {
    static let idleColor = UIColor(red:0.85,green:0.035,blue:0.055,alpha:1)
    static let windupColor = UIColor(red:1,green:0.3,blue:0.08,alpha:1)
    let id: Int
    let root = SCNNode()
    private let material = SCNMaterial()
    private var legs: [SCNNode] = []
    private var stepPhase: Float = 0
    private(set) var alive = false
    private(set) var position = SIMD3<Float>.zero
    var approaches = false
    var shotTimer = 0.0
    var windup: Double?
    var muzzle: SIMD3<Float> {
        let p = root.convertPosition(SCNVector3(0.28,1.26,-0.55),to:nil)
        return SIMD3(p.x,p.y,p.z)
    }
    var hitCenter: SIMD3<Float> { position+SIMD3(0,1.05,0) }
    var targets: [SphereTarget] {
        [SphereTarget(id:id,center:position+SIMD3(0,1.06,0),radius:0.29),
         SphereTarget(id:id,center:position+SIMD3(0,1.62,0),radius:0.20),
         SphereTarget(id:id,center:position+SIMD3(0,0.48,0),radius:0.24)]
    }
    init(id: Int) {
        self.id = id
        material.lightingModel = .lambert; material.diffuse.contents = Self.idleColor
        func part(_ size: SIMD3<Float>, _ point: SIMD3<Float>, parent: SCNNode? = nil) -> SCNNode {
            let shape = SCNBox(width:CGFloat(size.x),height:CGFloat(size.y),length:CGFloat(size.z),chamferRadius:0.018)
            shape.chamferSegmentCount = 1; shape.firstMaterial = material
            let node = SCNNode(geometry:shape); node.simdPosition = point
            (parent ?? root).addChildNode(node); return node
        }
        let chest = part(SIMD3(0.45,0.56,0.24),SIMD3(0,1.12,0)); chest.eulerAngles.z = 0.025
        _ = part(SIMD3(0.31,0.24,0.23),SIMD3(0,0.73,0))
        let skull = SCNSphere(radius:0.18); skull.segmentCount = 6; skull.firstMaterial = material
        let head = SCNNode(geometry:skull); head.position = SCNVector3(0,1.62,0); head.eulerAngles.y = .pi/4
        root.addChildNode(head)
        for side in [Float(-1),1] {
            let hip = SCNNode(); hip.position = SCNVector3(side*0.12,0.7,0); root.addChildNode(hip); legs.append(hip)
            _ = part(SIMD3(0.14,0.31,0.15),SIMD3(0,-0.17,0),parent:hip)
            _ = part(SIMD3(0.11,0.32,0.12),SIMD3(0,-0.48,0.02),parent:hip)
            _ = part(SIMD3(0.14,0.10,0.25),SIMD3(0,-0.65,-0.05),parent:hip)
            let upper = part(SIMD3(0.12,0.30,0.14),SIMD3(side*0.28,1.24,-0.03)); upper.eulerAngles.x = -.pi/5
            let lower = part(SIMD3(0.10,0.12,0.33),SIMD3(side*0.28,1.19,-0.23)); lower.eulerAngles.x = -.pi/12
        }
        let gun = SCNBox(width:0.055,height:0.09,length:0.25,chamferRadius:0.008)
        gun.firstMaterial = tmConstantMaterial(UIColor(white:0.08,alpha:1))
        let weapon = SCNNode(geometry:gun); weapon.position = SCNVector3(0.28,1.26,-0.43); root.addChildNode(weapon)
        root.isHidden = true
    }
    func spawn(at point: SIMD3<Float>, approaches: Bool, firstShot: Double) {
        alive = true; self.approaches = approaches; shotTimer = firstShot; windup = nil; stepPhase = 0
        position = point; root.simdPosition = point; root.isHidden = false
        material.diffuse.contents = Self.idleColor
        for leg in legs { leg.eulerAngles.x = 0 }
    }
    func move(to point: SIMD3<Float>) { position = point; root.simdPosition = point }
    func animate(toward target: SIMD3<Float>, walking: Bool, dt: Double) {
        let d = target-position
        if d.x*d.x+d.z*d.z > 0.01 { root.eulerAngles.y = atan2(-d.x,-d.z) }
        stepPhase += Float(dt)*5
        for (index,leg) in legs.enumerated() { leg.eulerAngles.x = walking ? sin(stepPhase+Float(index) * .pi)*0.25 : 0 }
    }
    func setWindup(_ on: Bool) { material.diffuse.contents = on ? Self.windupColor : Self.idleColor }
    func die() { alive = false; windup = nil; root.isHidden = true }
}

