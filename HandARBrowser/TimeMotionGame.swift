    private func layout(headPosition: SIMD3<Float>, forward direction: SIMD3<Float>) {
        head = headPosition
        forward = direction
        right = simd_normalize(simd_cross(forward, up))
        floorY = headPosition.y - TMLayout.floorDepthBelowHead
        let basis = simd_quatf(simd_float3x3(columns: (right, up, -forward)))

        floorNode.simdPosition = place(TMLayout.arenaDistance, 0, 0)
        floorNode.simdOrientation = simd_quatf(angle: -.pi / 2, axis: SIMD3(1, 0, 0))

        backWall.simdPosition = place(9, 0, 2.5)
        backWall.simdOrientation = simd_quatf(from: SIMD3(0, 0, 1), to: -forward)
        leftWall.simdPosition = place(4, -8, 2.5)
        leftWall.simdOrientation = simd_quatf(from: SIMD3(0, 0, 1), to: right)
        rightWall.simdPosition = place(4, 8, 2.5)
        rightWall.simdOrientation = simd_quatf(from: SIMD3(0, 0, 1), to: -right)

        coverBoxes.removeAll()
        for (index, spec) in TimeMotionVRGame.coverSpecs.enumerated() {
            let center = place(spec.forward, spec.right, spec.halfHeight)
            coverNodes[index].simdPosition = center
            coverNodes[index].simdOrientation = basis
            coverBoxes.append(obstacle(center: center, halfRight: spec.halfRight,
                                       halfForward: spec.halfForward, halfHeight: spec.halfHeight))
        }

        items[0].home = place(0.9, 0.45, 0.95 + TMLayout.gunHalf.y)
        items[1].home = place(1.25, -0.2, TMLayout.cubeHalf.y)
        items[2].home = place(1.5, 0.6, TMLayout.cubeHalf.y)
        items[3].home = place(1.9, -0.9, TMLayout.cubeHalf.y)

        layoutButtons()
        let hudHeight: Float = 1.5
        scoreLabel.simdPosition = place(1.6, -0.9, hudHeight + 0.05)
        healthLabel.simdPosition = place(1.6, 0.9, hudHeight + 0.05)
        waveLabel.simdPosition = place(1.6, 0, hudHeight + 0.15)
        speedLabel.simdPosition = place(1.6, 0, hudHeight - 0.25)
        centerLabel.simdPosition = place(1.6, 0, hudHeight + 0.45)
        hintLabel.simdPosition = place(1.6, 0, 0.7)
    }

    private func layoutButtons() {
        let playing = phase == .playing
        buttons[0].node.isHidden = !playing
        buttons[2].node.isHidden = playing
        buttons[1].node.isHidden = false
        buttons[0].node.simdPosition = place(1.35, -0.45, 1.05)
        buttons[2].node.simdPosition = place(1.35, -0.45, 1.05)
        buttons[1].node.simdPosition = place(1.35, 0.45, 1.05)
    }

    private func place(_ forwardDistance: Float, _ rightDistance: Float, _ height: Float) -> SIMD3<Float> {
        SIMD3(head.x + forward.x * forwardDistance + right.x * rightDistance,
              floorY + height,
              head.z + forward.z * forwardDistance + right.z * rightDistance)
    }

    private func obstacle(center: SIMD3<Float>, halfRight: Float, halfForward: Float,
                          halfHeight: Float) -> BoxObstacle {
        var lo = center
        var hi = center
        for sideRight in [Float(-1), 1] {
            for sideForward in [Float(-1), 1] {
                let corner = center + right * (sideRight * halfRight) + forward * (sideForward * halfForward)
                lo = simd_min(lo, corner)
                hi = simd_max(hi, corner)
            }
        }
        lo.y = center.y - halfHeight
        hi.y = center.y + halfHeight
        return BoxObstacle(lo: lo, hi: hi)
    }

    private func syncNodes() {
        for item in items {
            item.node.simdPosition = item.position
            if item.isGun {
                item.node.simdOrientation = simd_quatf(from: SIMD3(0, 0, -1), to: item.aim)
            }
        }
    }

