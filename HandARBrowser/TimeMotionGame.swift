    // MARK: Lifecycle

    func start(in scene: SCNScene, headPosition: SIMD3<Float>, forward direction: SIMD3<Float>) {
        guard !isRunning else { return }
        buildArena()
        if root.parent == nil { scene.rootNode.addChildNode(root) }
        layout(headPosition: headPosition, forward: simd_normalize(SIMD3(direction.x, 0, direction.z)))
        best = TimeMotionBestScore.load()
        lastNow = nil
        isRunning = true
        resetRound()
    }

    func stop() {
        guard isRunning else { return }
        isRunning = false
        dropAll()
        for bullet in bullets { freeBullet(bullet.slot) }
        bullets.removeAll()
        for enemy in enemies { enemy.die() }
        for index in shards.indices {
            shards[index].active = false
            shards[index].node.isHidden = true
        }
        sounds.stopAll()
        dwellRing.isHidden = true
        root.removeFromParentNode()
        lastNow = nil
    }

    /// Called when hand input is interrupted. Stops firing at once and drops held objects.
    func cancelInput() {
        guard isRunning else { return }
        dropAll()
        buttonGate.cancel()
        dwellRing.isHidden = true
        gunFiring = false
        fire.rearm()
    }

    // MARK: Frame

    func update(now: Double, left: TimeMotionHandInput?, right: TimeMotionHandInput?,
                headTransform: simd_float4x4, trackingReady: Bool, dwell: Bool) {
        guard isRunning, now.isFinite else { return }
        let realDt = lastNow.map { min(max(now - $0, 0), TimeMotionTuning.maxRealStep) } ?? 0
        lastNow = now

        let c0 = headTransform.columns.0, c1 = headTransform.columns.1
        let c2 = headTransform.columns.2, c3 = headTransform.columns.3
        head = SIMD3(c3.x, c3.y, c3.z)
        let rotation = simd_quatf(simd_float3x3(columns: (SIMD3(c0.x, c0.y, c0.z),
                                                          SIMD3(c1.x, c1.y, c1.z),
                                                          SIMD3(c2.x, c2.y, c2.z))))
        var headSpeed = 0.0
        if let previous = lastHeadRotation, realDt > 0 {
            let agreement = min(1, abs(simd_dot(previous.vector, rotation.vector)))
            headSpeed = Double(2 * acos(agreement)) / realDt
        }
        lastHeadRotation = rotation

        var handSpeeds = [0.0, 0.0]
        for (index, entry) in [left, right].enumerated() {
            guard let input = entry, let pose = input.pose else {
                lastHandCenter[index] = nil
                handVelocity[index] = .zero
                continue
            }
            if let previous = lastHandCenter[index], realDt > 0 {
                let raw = (pose.center - previous) / Float(realDt)
                handVelocity[index] = handVelocity[index] * 0.6 + raw * 0.4
                handSpeeds[index] = Double(simd_length(handVelocity[index]))
            }
            lastHandCenter[index] = pose.center
        }

        let sample: MotionSample
        if !trackingReady {
            sample = .lost
        } else if headSpeed > TimeMotionTuning.headGlitch
                    || (handSpeeds.max() ?? 0) > TimeMotionTuning.handGlitch {
            sample = .glitch
        } else {
            sample = .motion(head: headSpeed, hand: handSpeeds.max() ?? 0)
        }
        timeScale.update(sample, realDt: realDt)

        processHands(left: left, right: right, handSpeeds: handSpeeds, now: now,
                     ready: trackingReady, dwell: dwell)
        guard isRunning else { return }

        let effective = (userPaused || phase != .playing) ? 0 : timeScale.scale
        let steps = clock.advance(realDt: realDt, scale: effective)
        for _ in 0..<steps where phase == .playing {
            simulateStep(TimeMotionTuning.fixedStep)
        }
        if !gunFiring { fire.rearm() }
        syncNodes()
        refreshHUD(now: now, effectiveScale: effective)
    }

    // MARK: Hands

    private func processHands(left: TimeMotionHandInput?, right: TimeMotionHandInput?,
                              handSpeeds: [Double], now: Double, ready: Bool, dwell: Bool) {
        let inputs = [left, right]
        gunFiring = false

        var pressing: TimeMotionHandInput?
        var targetButton: Int?
        if ready, let input = inputs.compactMap({ $0 }).first(where: { $0.aimRay != nil }),
           let ray = input.aimRay {
            pressing = input
            targetButton = buttonHit(ray: ray)
        }
        for id in buttons.indices { buttons[id].setHighlight(id == targetButton) }

        let committed = buttonGate.update(target: targetButton, down: pressing?.pinch ?? false,
                                          allowBegin: true, dwell: dwell, at: now)
        dwellRing.show(on: targetButton.map { buttons[$0].node }, progress: buttonGate.dwellProgress)
        if let committed {
            handleButton(committed)
            if !isRunning { return }
        }

        for index in 0..<2 {
            let input = inputs[index]
            let reliable = ready && input?.pose != nil
            var target: Int?
            if reliable, phase == .playing, !userPaused, targetButton == nil,
               grabGates[index].held == nil, let ray = input?.aimRay {
                target = freeItem(for: ray)
            }
            let event = grabGates[index].update(target: target, fist: input?.fist ?? false,
                                                open: input?.open ?? false, reliable: reliable,
                                                blocked: false, at: now)
            switch event {
            case let .began(id):
                items[id].held = handFor(index)
                items[id].resting = false
                items[id].velocity = .zero
                sounds.play(.grab, volume: 0.6)
            case let .released(id):
                items[id].held = nil
                items[id].resting = false
                items[id].velocity = clampedThrow(handVelocity[index])
                sounds.play(.release, volume: 0.5)
            case let .cancelled(id):
                items[id].held = nil
                items[id].resting = false
                items[id].velocity = .zero
            case .none:
                break
            }

            if let heldID = grabGates[index].held, reliable, let pose = input?.pose {
                let item = items[heldID]
                let aim = aimDirection(for: pose)
                item.aim = aim
                item.position = item.isGun ? pose.center + aim * 0.07 : pose.center
                item.velocity = .zero
                item.resting = false
                if heldID == 0, grabGates[index].releaseProgress == 0, phase == .playing, !userPaused {
                    gunFiring = true
                }
            }

            if ready, phase == .playing, let input, let pose = input.pose,
               handSpeeds[index] >= 0.9 {
                punch(with: pose.center, hand: index, speed: handSpeeds[index], now: now)
            }
        }
    }

    private func punch(with point: SIMD3<Float>, hand: Int, speed: Double, now: Double) {
        for enemy in enemies where enemy.alive {
            guard simd_length(point - enemy.hitCenter) <= TMLayout.enemyHitRadius + 0.1 else { continue }
            if meleeGate.allows(key: enemy.id * 2 + hand, handSpeed: speed, at: now) {
                killEnemy(enemy)
            }
        }
    }

    private func freeItem(for ray: WorldRay) -> Int? {
        var nearest: (index: Int, t: Float)?
        for (index, item) in items.enumerated() where item.held == nil {
            guard let t = GraffitiPropGeometry.rayDistance(origin: ray.origin, direction: ray.direction,
                                                           center: item.position, radius: item.radius) else { continue }
            if nearest == nil || t < nearest!.t { nearest = (index, t) }
        }
        return nearest?.index
    }

    private func buttonHit(ray: WorldRay) -> Int? {
        var nearest: (id: Int, t: Float)?
        for id in visibleButtonIDs() {
            guard let t = GraffitiPropGeometry.rayDistance(origin: ray.origin, direction: ray.direction,
                                                           center: buttons[id].node.simdWorldPosition,
                                                           radius: TMLayout.buttonRadius) else { continue }
            if nearest == nil || t < nearest!.t { nearest = (id, t) }
        }
        return nearest?.id
    }

    private func visibleButtonIDs() -> [Int] {
        phase == .playing ? [0, 1] : [2, 1]
    }

    private func handleButton(_ id: Int) {
        switch id {
        case 0:
            userPaused.toggle()
            buttons[0].setTitle(userPaused ? "▶ ДАЛЬШЕ" : "Ⅱ ПАУЗА")
            showTransient(userPaused ? "Пауза: время остановлено" : "Продолжаем")
        case 1:
            onExitRequested?()
        case 2:
            resetRound()
        default:
            break
        }
    }

    private func handFor(_ index: Int) -> TrackedHand {
        index == 0 ? .left : .right
    }

    private func aimDirection(for pose: VirtualHandPose) -> SIMD3<Float> {
        if let wrist = pose.points[0], let tip = pose.points[8] {
            let delta = tip - wrist
            let length = simd_length(delta)
            if length > 0.01 { return delta / length }
        }
        return pose.along
    }

    private func clampedThrow(_ velocity: SIMD3<Float>) -> SIMD3<Float> {
        let length = simd_length(velocity)
        guard length.isFinite, length > 0 else { return .zero }
        return velocity * min(1, TMLayout.throwSpeedLimit / length)
    }

    // MARK: Simulation (fixed game steps)

    private func simulateStep(_ dt: Double) {
        let alive = enemies.filter { $0.alive }.count
        switch director.tick(gameDt: dt, alive: alive) {
        case let .spawn(wave):
            spawnEnemy(wave: wave)
        case let .waveCleared(wave):
            score.addWaveCleared()
            showTransient("Волна \(wave + 1) пройдена +\(TimeMotionScore.waveBonus)")
            sounds.play(.thud, volume: 0.5)
        case .victory:
            finish(won: true)
        case .none:
            break
        }
        guard phase == .playing else { return }

        updateEnemies(dt)
        updateBullets(dt)
        guard phase == .playing else { return }
        updateItems(dt)
        updateShards(dt)
        if fire.advance(gameDt: dt, firing: gunFiring) {
            fireGun()
        }
    }

    private func spawnEnemy(wave: Int) {
        guard let enemy = enemies.first(where: { !$0.alive }) else { return }
        let angle = Float.random(in: -0.95...0.95)
        let distance = Float.random(in: 3.8...6.2)
        let point = place(distance * cos(angle), distance * sin(angle), 0)
        enemy.spawn(at: point, approaches: Float.random(in: 0...1) < 0.4,
                    firstShot: Double.random(in: 1.2...2.2))
    }

    private func updateEnemies(_ dt: Double) {
        for enemy in enemies where enemy.alive {
            if enemy.approaches {
                let toHead = SIMD3(head.x - enemy.hitCenter.x, 0, head.z - enemy.hitCenter.z)
                let distance = simd_length(toHead)
                if distance > 2.4 {
                    let step = simd_normalize(toHead) * Float(0.35 * dt)
                    enemy.move(to: enemy.root.simdPosition + step)
                }
            }
            if let windup = enemy.windup {
                let next = windup - dt
                if next <= 0 {
                    enemy.windup = nil
                    enemy.setWindup(false)
                    shootAtHead(from: enemy)
                } else {
                    enemy.windup = next
                }
            } else {
                enemy.shotTimer -= dt
                if enemy.shotTimer <= 0 {
                    enemy.windup = TMLayout.windupSeconds
                    enemy.setWindup(true)
                    enemy.shotTimer = Double.random(in: 1.8...2.8)
                }
            }
        }
    }

    private func shootAtHead(from enemy: TMEnemy) {
        let muzzle = enemy.root.simdPosition + SIMD3(0, 1.25, 0)
        let target = head - SIMD3(0, 0.05, 0)
        let delta = target - muzzle
        let length = simd_length(delta)
        guard length > 0.01 else { return }
        if spawnBullet(owner: .enemy, position: muzzle, velocity: delta / length * TMLayout.enemyBulletSpeed,
                       lifetime: TMLayout.enemyBulletLifetime) {
            sounds.play(.enemyShot, volume: 0.4)
        }
    }

    private func fireGun() {
        let gun = items[0]
        let muzzle = gun.position + gun.aim * 0.09
        if spawnBullet(owner: .player, position: muzzle, velocity: gun.aim * TMLayout.playerBulletSpeed,
                       lifetime: TMLayout.playerBulletLifetime) {
            sounds.play(.shot, volume: 0.8)
        }
    }

    @discardableResult
    private func spawnBullet(owner: ProjectileOwner, position: SIMD3<Float>,
                             velocity: SIMD3<Float>, lifetime: Double) -> Bool {
        guard let slot = freeBulletSlots.popLast() else { return false }
        let node = bulletNodes[slot]
        node.geometry?.firstMaterial = owner == .player ? playerBulletMaterial : enemyBulletMaterial
        node.simdPosition = position
        node.isHidden = false
        bullets.append(TMBullet(state: ProjectileState(position: position, velocity: velocity,
                                                       owner: owner, lifetime: lifetime),
                                slot: slot))
        return true
    }

    private func freeBullet(_ slot: Int) {
        bulletNodes[slot].isHidden = true
        freeBulletSlots.append(slot)
    }

    private func updateBullets(_ dt: Double) {
        let enemySpheres = enemies.filter { $0.alive }.map {
            SphereTarget(id: $0.id, center: $0.hitCenter, radius: TMLayout.enemyHitRadius)
        }
        let headSphere = SphereTarget(id: -1, center: head, radius: TMLayout.headRadius)
        var kept: [TMBullet] = []
        kept.reserveCapacity(bullets.count)
        for var bullet in bullets {
            let segment = bullet.state.step(gameDt: dt)
            bulletNodes[bullet.slot].simdPosition = bullet.state.position
            let playerHead: SphereTarget? = bullet.state.owner == .enemy ? headSphere : nil
            if let hit = ProjectileRules.firstImpact(owner: bullet.state.owner, from: segment.from,
                                                     to: segment.to, covers: coverBoxes,
                                                     enemies: enemySpheres, playerHead: playerHead) {
                freeBullet(bullet.slot)
                switch hit.impact {
                case .cover:
                    break
                case let .enemy(id):
                    if let enemy = enemies.first(where: { $0.id == id && $0.alive }) {
                        killEnemy(enemy)
                    }
                case .player:
                    playerHit()
                }
                continue
            }
            if bullet.state.expired {
                freeBullet(bullet.slot)
                continue
            }
            kept.append(bullet)
        }
        bullets = kept
    }

    private func playerHit() {
        sounds.play(.hit, volume: 0.9)
        if health.takeHit() {
            finish(won: false)
        } else {
            showTransient("Попадание! Уворачивайся головой")
        }
    }

    private func killEnemy(_ enemy: TMEnemy) {
        let center = enemy.hitCenter
        enemy.die()
        score.addKill()
        spawnShards(at: center)
        sounds.play(.shatter, volume: 0.8)
    }

    private func spawnShards(at center: SIMD3<Float>) {
        var spawned = 0
        for index in shards.indices where !shards[index].active && spawned < 10 {
            shards[index].active = true
            shards[index].ttl = 0.6
            shards[index].velocity = SIMD3(Float.random(in: -2...2), Float.random(in: 1...3), Float.random(in: -2...2))
            shards[index].node.simdPosition = center
            shards[index].node.isHidden = false
            spawned += 1
        }
    }

    private func updateShards(_ dt: Double) {
        for index in shards.indices where shards[index].active {
            shards[index].velocity.y -= TMLayout.gravity * Float(dt)
            var position = shards[index].node.simdPosition + shards[index].velocity * Float(dt)
            if position.y < floorY + 0.03 {
                position.y = floorY + 0.03
                shards[index].velocity = .zero
            }
            shards[index].node.simdPosition = position
            shards[index].ttl -= dt
            if shards[index].ttl <= 0 {
                shards[index].active = false
                shards[index].node.isHidden = true
            }
        }
    }

    private func updateItems(_ dt: Double) {
        for item in items where item.held == nil && !item.resting {
            let previous = item.position
            item.velocity.y -= TMLayout.gravity * Float(dt)
            item.position += item.velocity * Float(dt)
            var supported = false
            let floorLevel = floorY + item.half.y
            if item.position.y <= floorLevel {
                item.position.y = floorLevel
                if item.velocity.y < 0 { item.velocity.y = -item.velocity.y * TMLayout.itemBounce }
                let friction = max(0, 1 - 6 * Float(dt))
                item.velocity.x *= friction
                item.velocity.z *= friction
                supported = true
            }
            for box in coverBoxes {
                let center = (box.lo + box.hi) * 0.5
                let half = (box.hi - box.lo) * 0.5
                let delta = item.position - center
                let overlap = half + item.half - SIMD3(abs(delta.x), abs(delta.y), abs(delta.z))
                guard overlap.x > 0, overlap.y > 0, overlap.z > 0 else { continue }
                var axis = 0
                if overlap.y < overlap[axis] { axis = 1 }
                if overlap.z < overlap[axis] { axis = 2 }
                let direction: Float = delta[axis] >= 0 ? 1 : -1
                item.position[axis] += direction * overlap[axis]
                if item.velocity[axis] * direction < 0 {
                    item.velocity[axis] *= -TMLayout.itemBounce
                }
                if axis == 1 && direction > 0 { supported = true }
            }
            let offset = SIMD3(item.position.x - head.x, 0, item.position.z - head.z)
            let distance = simd_length(offset)
            if distance > 7 {
                let scale = 7 / distance
                item.position.x = head.x + offset.x * scale
                item.position.z = head.z + offset.z * scale
                item.velocity.x *= 0.3
                item.velocity.z *= 0.3
            }
            let horizontal = simd_length(SIMD3(item.velocity.x, 0, item.velocity.z))
            if supported, abs(item.velocity.y) < 0.25, horizontal < 0.08 {
                item.resting = true
                item.velocity = .zero
            }
            if simd_length(item.velocity) > 1.6 {
                for enemy in enemies where enemy.alive {
                    if TimeMotionGeometry.segmentSphere(from: previous, to: item.position, center: enemy.hitCenter,
                                                        radius: TMLayout.enemyHitRadius + item.radius) != nil {
                        killEnemy(enemy)
                        item.velocity *= 0.3
                        break
                    }
                }
            }
        }
    }

    private func finish(won: Bool) {
        guard phase == .playing else { return }
        phase = won ? .victory : .defeat
        if won {
            score.addVictory()
            sounds.play(.win, volume: 0.9)
        } else {
            sounds.play(.lose, volume: 0.9)
        }
        userPaused = false
        dropAll()
        if TimeMotionBestScore.record(score.points) { best = score.points }
        best = max(best, score.points)
        buttons[0].setTitle("Ⅱ ПАУЗА")
        layoutButtons()
    }

    // MARK: Round state

    private func resetRound() {
        dropAll()
        phase = .playing
        userPaused = false
        score = TimeMotionScore()
        health = PlayerHealth()
        director = WaveDirector()
        timeScale.reset()
        clock.reset()
        fire = FireScheduler()
        meleeGate.reset()
        buttonGate = ReleaseClickGate<Int>()
        gunFiring = false
        for enemy in enemies { enemy.die() }
        for bullet in bullets { freeBullet(bullet.slot) }
        bullets.removeAll()
        for index in shards.indices {
            shards[index].active = false
            shards[index].node.isHidden = true
        }
        for item in items {
            item.held = nil
            item.velocity = .zero
            item.resting = true
            item.position = item.home
        }
        items[0].aim = forward
        lastHeadRotation = nil
        lastHandCenter = [nil, nil]
        handVelocity = [.zero, .zero]
        buttons[0].setTitle("Ⅱ ПАУЗА")
        layoutButtons()
        showTransient("Волна 1 · кулак — взять · открытая ладонь 2 с — отпустить")
    }

    private func dropAll() {
        for index in 0..<2 {
            if let id = grabGates[index].held {
                items[id].held = nil
                items[id].resting = false
                items[id].velocity = .zero
            }
            _ = grabGates[index].cancel()
        }
    }

    private func showTransient(_ text: String) {
        transientText = text
        transientUntil = (lastNow ?? 0) + TMLayout.transientSeconds
    }

