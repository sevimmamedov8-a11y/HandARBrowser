private final class TMEnemy {
    static let idleColor = UIColor(red: 1.0, green: 0.22, blue: 0.22, alpha: 1)
    static let windupColor = UIColor(red: 1.0, green: 0.62, blue: 0.2, alpha: 1)

    let id: Int
    let root = SCNNode()
    private let material: SCNMaterial
    private(set) var alive = false
    private(set) var position = SIMD3<Float>.zero
    var approaches = false
    var shotTimer = 0.0
    var windup: Double?

    init(id: Int) {
        self.id = id
        material = tmConstantMaterial(TMEnemy.idleColor)
        let body = SCNNode(geometry: SCNCapsule(capRadius: 0.2, height: 1.1))
        body.geometry?.firstMaterial = material
        body.simdPosition = SIMD3(0, 0.85, 0)
        let head = SCNNode(geometry: SCNSphere(radius: 0.15))
        head.geometry?.firstMaterial = material
        head.simdPosition = SIMD3(0, 1.6, 0)
        root.addChildNode(body)
        root.addChildNode(head)
        root.isHidden = true
    }

    var hitCenter: SIMD3<Float> { position + SIMD3(0, 0.95, 0) }

    func spawn(at point: SIMD3<Float>, approaches: Bool, firstShot: Double) {
        alive = true
        self.approaches = approaches
        shotTimer = firstShot
        windup = nil
        position = point
        material.diffuse.contents = TMEnemy.idleColor
        root.simdPosition = point
        root.isHidden = false
    }

    func move(to point: SIMD3<Float>) {
        position = point
        root.simdPosition = point
    }

    func setWindup(_ on: Bool) {
        material.diffuse.contents = on ? TMEnemy.windupColor : TMEnemy.idleColor
    }

    func die() {
        alive = false
        windup = nil
        root.isHidden = true
    }
}

