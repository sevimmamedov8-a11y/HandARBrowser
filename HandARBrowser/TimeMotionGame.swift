    private func clampedThrow(_ velocity: SIMD3<Float>) -> SIMD3<Float> {
        let length = simd_length(velocity)
        guard length.isFinite, length > 0 else { return .zero }
        return velocity * min(1, TMLayout.throwSpeedLimit / length)
    }

    // MARK: Simulation (fixed game steps)

    private func simulateStep(_ dt: Double) {
        playerTime += dt
        let alive = enemies.filter { $0.alive }.count
        switch director.tick(gameDt: dt, alive: alive) {
        case let .spawn(wave):
            spawnEnemy(wave: wave)
        case let .waveCleared(wave):
            score.addWaveCleared()
            showTransient("Волна \(wave + 1) пройдена +\(TimeMotionScore.waveBonus)")
            sounds.play(.thud, volume: 0.5)
        case .victory:
            finish(won: true)
        case .none:
            break
        }
        guard phase == .playing else { return }

        updateEnemies(dt)
        updateBullets(dt)
        guard phase == .playing else { return }
        updateItems(dt)
        updateShards(dt)
        if fire.advance(gameDt: dt, firing: gunFiring) {
            fireGun()
        }
    }

    private func spawnEnemy(wave: Int) {
        guard let enemy = enemies.first(where: { !$0.alive }) else { return }
        let pads: [(Float,Float)] = [(4.3,-2.5),(4.8,2.6),(6.3,0),(6.5,-3.3),(6.8,3.2),(3.8,-3.7),(4.1,3.8)]
        for offset in 0..<pads.count {
            let pad = pads[(spawnIndex+offset)%pads.count], point = place(pad.0,pad.1,0)
            if enemies.contains(where: { $0.alive && simd_length($0.position-point)<0.8 }) { continue }
            enemy.spawn(at:point,approaches:(spawnIndex+wave)%3 != 0,firstShot:1.5+Double(spawnIndex%3)*0.35)
            spawnIndex += offset+1; return
        }
    }

    private func updateEnemies(_ dt: Double) {
        for enemy in enemies where enemy.alive {
            if enemy.approaches {
                let toHead = SIMD3(head.x - enemy.hitCenter.x, 0, head.z - enemy.hitCenter.z)
                let distance = simd_length(toHead)
                if distance > 2.4 {
                    let step = simd_normalize(toHead) * Float(0.35 * dt)
                    let candidate = enemy.position+step
                    let chest = candidate+SIMD3(0,0.9,0)
                    let blocked = coverBoxes.contains { TimeMotionGeometry.hitBox(from:enemy.hitCenter,to:chest,box:$0,padding:0.24) != nil }
                    if !blocked { enemy.move(to:candidate) }
                }
            }
            enemy.animate(toward:head,walking:enemy.approaches && simd_length(head-enemy.hitCenter)>2.4,dt:dt)
            if let windup = enemy.windup {
                let next = windup - dt
                if next <= 0 {
                    enemy.windup = nil
                    enemy.setWindup(false)
                    shootAtHead(from: enemy)
                } else {
                    enemy.windup = next
                }
            } else {
                enemy.shotTimer -= dt
                if enemy.shotTimer <= 0 {
                    enemy.windup = TMLayout.windupSeconds
                    enemy.setWindup(true)
                    enemy.shotTimer = Double.random(in: 1.8...2.8)
                }
            }
        }
    }

    private func shootAtHead(from enemy: TMEnemy) {
        let muzzle = enemy.muzzle
        let target = head - SIMD3(0, 0.05, 0)
        let delta = target - muzzle
        let length = simd_length(delta)
        guard length > 0.01 else { return }
        if spawnBullet(owner: .enemy, position: muzzle, velocity: delta / length * TMLayout.enemyBulletSpeed,
                       lifetime: TMLayout.enemyBulletLifetime) {
            sounds.play(.enemyShot, volume: 0.4)
        }
    }

    private func fireGun() {
        let gun = items[0]
        let muzzle = gun.position + gun.aim * 0.14
        if spawnBullet(owner: .player, position: muzzle, velocity: gun.aim * TMLayout.playerBulletSpeed,
                       lifetime: TMLayout.playerBulletLifetime) {
            sounds.play(.shot, volume: 0.65); shotFlash = 0.065
        }
    }

    @discardableResult
    private func spawnBullet(owner: ProjectileOwner, position: SIMD3<Float>,
                             velocity: SIMD3<Float>, lifetime: Double) -> Bool {
        guard let slot = freeBulletSlots.popLast() else { return false }
        let node = bulletNodes[slot]
        node.geometry?.firstMaterial = owner == .player ? playerBulletMaterial : enemyBulletMaterial
        node.simdPosition = position
        node.simdOrientation = simd_quatf(from:SIMD3(0,0,-1),to:simd_normalize(velocity))
        node.isHidden = false
        bullets.append(TMBullet(state: ProjectileState(position: position, velocity: velocity,
                                                       owner: owner, lifetime: lifetime),
                                slot: slot))
        return true
    }

    private func freeBullet(_ slot: Int) {
        bulletNodes[slot].isHidden = true
        freeBulletSlots.append(slot)
    }

    private func updateBullets(_ dt: Double) {
        let enemySpheres = enemies.filter { $0.alive }.flatMap { $0.targets }
        let headSphere = SphereTarget(id: -1, center: head, radius: TMLayout.headRadius)
        var kept: [TMBullet] = []
        kept.reserveCapacity(bullets.count)
        for var bullet in bullets {
            let segment = bullet.state.step(gameDt: dt)
            bulletNodes[bullet.slot].simdPosition = bullet.state.position
            let playerHead: SphereTarget? = bullet.state.owner == .enemy ? headSphere : nil
            if let hit = ProjectileRules.firstImpact(owner: bullet.state.owner, from: segment.from,
                                                     to: segment.to, covers: coverBoxes,
                                                     enemies: enemySpheres, playerHead: playerHead) {
                freeBullet(bullet.slot)
                switch hit.impact {
                case .cover:
                    break
                case let .enemy(id):
                    if let enemy = enemies.first(where: { $0.id == id && $0.alive }) {
                        killEnemy(enemy)
                    }
                case .player:
                    playerHit()
                }
                continue
            }
            if bullet.state.expired {
                freeBullet(bullet.slot)
                continue
            }
            kept.append(bullet)
        }
        bullets = kept
    }

    private func playerHit() {
        guard phase == .playing, playerTime-lastDamage > 0.65 else { return }
        lastDamage = playerTime
        sounds.play(.hit, volume: 0.65)
        if health.takeHit() {
            finish(won: false)
        } else {
            showTransient("Попадание! Уворачивайся головой")
        }
    }

    private func killEnemy(_ enemy: TMEnemy) {
        guard enemy.alive, phase == .playing else { return }
        let center = enemy.hitCenter
        enemy.die()
        score.addKill()
        spawnShards(at: center)
        sounds.play(.shatter, volume: 0.8)
    }

    private func spawnShards(at center: SIMD3<Float>) {
        var spawned = 0
        for index in shards.indices where !shards[index].active && spawned < 10 {
            shards[index].active = true
            shards[index].ttl = 0.6
            shards[index].velocity = SIMD3(Float.random(in: -2...2), Float.random(in: 1...3), Float.random(in: -2...2))
            shards[index].node.simdPosition = center
            shards[index].node.isHidden = false
            spawned += 1
        }
    }

    private func updateShards(_ dt: Double) {
        for index in shards.indices where shards[index].active {
            shards[index].velocity.y -= TMLayout.gravity * Float(dt)
            var position = shards[index].node.simdPosition + shards[index].velocity * Float(dt)
            if position.y < floorY + 0.03 {
                position.y = floorY + 0.03
                shards[index].velocity = .zero
            }
            shards[index].node.simdPosition = position
            shards[index].node.simdEulerAngles += SIMD3(Float(dt)*2,Float(dt)*3,Float(dt))
            shards[index].ttl -= dt
            if shards[index].ttl <= 0 {
                shards[index].active = false
                shards[index].node.isHidden = true
            }
        }
    }

    private func updateItems(_ dt: Double) {
        for item in items where item.held == nil && !item.resting {
            let previous = item.position
            item.velocity.y -= TMLayout.gravity * Float(dt)
            item.position += item.velocity * Float(dt)
            item.angles += item.spin*Float(dt); item.spin *= max(0,1-Float(dt)*0.4)
            var supported = false
            let bounds = GraffitiFlight.extent(half:item.half,angles:item.angles)
            let floorLevel = floorY + bounds.y
            if item.position.y <= floorLevel {
                item.position.y = floorLevel
                if item.velocity.y < 0 { item.velocity.y = -item.velocity.y * TMLayout.itemBounce }
                let friction = max(0, 1 - 6 * Float(dt))
                item.velocity.x *= friction
                item.velocity.z *= friction
                supported = true
            }
            for box in coverBoxes {
                let half = (box.hi - box.lo) * 0.5
                let delta = box.local(item.position)
                let horizontal = max(bounds.x,bounds.z)
                let overlap = half + SIMD3(horizontal,bounds.y,horizontal) - SIMD3(abs(delta.x),abs(delta.y),abs(delta.z))
                guard overlap.x > 0, overlap.y > 0, overlap.z > 0 else { continue }
                var axis = 0
                if overlap.y < overlap[axis] { axis = 1 }
                if overlap.z < overlap[axis] { axis = 2 }
                let direction: Float = delta[axis] >= 0 ? 1 : -1
                var localNormal = SIMD3<Float>.zero; localNormal[axis] = direction
                let normal = box.worldVector(localNormal)
                item.position += normal*overlap[axis]
                let incoming = simd_dot(item.velocity,normal)
                if incoming < 0 { item.velocity -= normal*incoming*(1+TMLayout.itemBounce) }
                if axis == 1 && direction > 0 { supported = true }
            }
            let offset = SIMD3(item.position.x - origin.x, 0, item.position.z - origin.z)
            let distance = simd_length(offset)
            if distance > 7 {
                let scale = 7 / distance
                item.position.x = origin.x + offset.x * scale
                item.position.z = origin.z + offset.z * scale
                item.velocity.x *= 0.3
                item.velocity.z *= 0.3
            }
            let horizontal = simd_length(SIMD3(item.velocity.x, 0, item.velocity.z))
            if supported, abs(item.velocity.y) < 0.25, horizontal < 0.08 {
                item.resting = true
                item.velocity = .zero
            }
            if simd_length(item.velocity) > 1.6 {
                for enemy in enemies where enemy.alive {
                    if enemy.targets.contains(where: { TimeMotionGeometry.segmentSphere(from:previous,to:item.position,center:$0.center,radius:$0.radius+item.radius) != nil }) && !coverBoxes.contains(where: { TimeMotionGeometry.hitBox(from:previous,to:item.position,box:$0) != nil }) {
                        killEnemy(enemy)
                        item.velocity *= 0.3
                        break
                    }
                }
            }
        }
    }

    private func finish(won: Bool) {
        guard phase == .playing else { return }
        phase = won ? .victory : .defeat
        if won {
            score.addVictory()
            sounds.play(.win, volume: 0.9)
        } else {
            sounds.play(.lose, volume: 0.9)
        }
        userPaused = false
        gunFiring = false; fire.rearm(); reticle.isHidden = true
        dropAll()
        if TimeMotionBestScore.record(score.points) { best = score.points }
        best = max(best, score.points)
        buttons[0].setTitle("Ⅱ ПАУЗА")
        layoutButtons()
    }

