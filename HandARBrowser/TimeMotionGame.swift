        grip.geometry?.firstMaterial = tmConstantMaterial(UIColor(red: 0.23, green: 0.25, blue: 0.28, alpha: 1))
        grip.simdPosition = SIMD3(0, -0.07, 0.04)
        gun.addChildNode(grip)
        let gunItem = TMItem(isGun: true, node: gun)
        items.append(gunItem)

        for _ in 0..<3 {
            let cube = SCNNode(geometry: SCNBox(width: 0.12, height: 0.12, length: 0.12, chamferRadius: 0.012))
