        for enemy in enemies { enemy.die() }
        for index in shards.indices {
            shards[index].active = false
            shards[index].node.isHidden = true
        }
        sounds.stopAll()
        dwellRing.isHidden = true
        root.removeFromParentNode()
        lastNow = nil
    }

